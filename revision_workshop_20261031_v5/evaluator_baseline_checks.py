"""Local, read-only source diagnostics for the independent thesis evaluator.

Standard-library Python only. PDF JSON is extracted locally with PDFKit.
Counts flag passages for human review; they are not quality scores.
"""
from pathlib import Path
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = Path('/Users/jollibear/Documents/tmp/phd thesis')
LOCAL = Path(__file__).resolve().parent
PDF_INPUTS = {
    'z_he':'Z_He_PhD_Thesis.pdf',
    'current':'main.pdf',
    'report1':'Preliminary_Report_PhD_thesis_Zhanhong_He 1.pdf',
    'report2':'Preliminary_Report_PhD_thesis_Zhanhong_He 2.pdf',
    'paper_cmmr':'publish_paper/2025_CMMR_MIDI_Velocity_Colorizer.pdf',
    'paper_smc':'publish_paper/2026_SMC_Score_Informed_Velocity.pdf',
    'paper_ismir':'publish_paper/2026_ISMIR_Cross_Instrument_Velocity.pdf',
}

def ensure_pdf_records():
    missing=[label for label in PDF_INPUTS if not (LOCAL/f'evaluator_{label}.json').exists()]
    if not missing:
        return
    binary=Path('/tmp/thesis-evaluator-extract')
    env=dict(os.environ)
    env.update(CLANG_MODULE_CACHE_PATH='/tmp/thesis-evaluator-modulecache',
               SWIFT_MODULECACHE_PATH='/tmp/thesis-evaluator-modulecache')
    subprocess.run(['/usr/bin/swiftc',str(LOCAL/'evaluator_extract.swift'),'-o',str(binary)],check=True,env=env)
    for label in missing:
        subprocess.run([str(binary),str(ROOT/PDF_INPUTS[label]),str(LOCAL/f'evaluator_{label}.json')],check=True)

def normalise(value):
    return re.sub(r'\s+', ' ', value).strip()

def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

QUOTES = [
    ('Chapter_3/chap3.tex', 'A MUSHRA-inspired reference-based listening test was conducted to evaluate the human-likeness of performances generated by U-Net, ConvAE \\cite{kuo2021velocity}, and the Flat model.'),
    ('Chapter_3/chap3.tex', 'The test used eight 10-second MIDI segments, each selected from one of the SMD performances listed in Table~\\ref{tab:velcomp_composers}.'),
    ('Chapter_7/Conclusion.tex', 'yet the listening test shows a clear improvement over flat and sequence-oriented baselines.'),
    ('Chapter_6/chap6.tex', '\\caption{An encoder-only Transformer maps padded note sequences to per-note PHE/OSF targets extracted from SoundFont-rendered audio.}'),
    ('Chapter_1/Intro.tex', 'MIDI velocity is a universal loudness variable for all instruments in digital audio workstations (DAWs)'),
    ('Chapter_1/Intro.tex', 'independent, static integer representing its initial strike force.'),
    ('Chapter_1/Intro.tex', 'large-scale non-piano score-dynamics transcription with human labels remains outside the scope'),
    ('Chapter_7/Conclusion.tex', 'These boundaries are not artefacts of unfinished implementation;'),
    ('Chapter_7/Conclusion.tex', 'These directions extend the thesis argument rather than repair it.'),
    ('Chapter_3/chap3.tex', 'roughly four measures at 120 BPM'),
    ('Chapter_6/chap6.tex', 'whose dynamic shape resembles the ground truth in panel (a).'),
]

def main():
    ensure_pdf_records()
    quote_checks=[]
    for rel, quote in QUOTES:
        text=(ROOT/rel).read_text()
        pos=text.find(quote)
        quote_checks.append(dict(source=rel, quote=quote, exact_match=pos>=0,
                                 line=text[:pos].count('\n')+1 if pos>=0 else None))
    if not all(x['exact_match'] for x in quote_checks):
        raise ValueError('A baseline quotation is not exact')
    report=json.loads((LOCAL/'evaluator_report1.json').read_text())
    unique=list(dict.fromkeys(a for p in report['pages'] for a in p['annotations']))
    md=normalise(re.sub(r'(?m)^> ?', '', (ROOT/'README_Preliminary_Report_1.md').read_text()))
    annotation_matches=[normalise(a) in md for a in unique]
    if not all(annotation_matches):
        raise ValueError('Report annotation and Markdown transcription differ')
    source_files=[ROOT/'main.tex',ROOT/'README.md',ROOT/'README_Preliminary_Report_1.md',
                  ROOT/'README_Preliminary_Report_2.md']
    source_files += sorted(ROOT.glob('Chapter_*/*.tex'))
    source_files += sorted(ROOT.glob('*.pdf')) + sorted((ROOT/'publish_paper').glob('*.pdf'))
    source_manifest={str(p.relative_to(ROOT)):sha256(p) for p in source_files}
    previous_manifest={str(p.relative_to(ROOT)):sha256(p) for p in sorted((ROOT/'revision_blueprint_20261031').rglob('*')) if p.is_file()}
    term_patterns={
        'renderer_conditioned':r'renderer-conditioned',
        'coordinate_family':r'\bcoordinates?\b',
        'most_controlled':r'\bmost controlled\b',
        'most_constrained':r'\bmost constrained\b',
        'defensive_unfinished':r'not artefacts of unfinished implementation',
        'defensive_repair':r'rather than repair it',
    }
    term_counts={str(p.relative_to(ROOT)):{name:len(re.findall(pattern,p.read_text(),re.I)) for name,pattern in term_patterns.items()} for p in sorted(ROOT.glob('Chapter_*/*.tex'))}
    pdfs={}
    for label in PDF_INPUTS:
        p=LOCAL/f'evaluator_{label}.json'
        d=json.loads(p.read_text())
        pdfs[label]={'source':d['source'],'page_count':d['pageCount'],
                     'annotation_objects_with_contents':sum(len(x['annotations']) for x in d['pages'])}
    result={
        'scope':'Source-only baseline; no prior proposals or recommendations read.',
        'source_manifest':source_manifest,
        'previous_proposal_manifest':previous_manifest,
        'quote_checks':quote_checks,
        'report1_annotation_verification':{'annotation_objects_with_contents':sum(len(x['annotations']) for x in report['pages']), 'unique_contents':len(unique),'matching_markdown_transcriptions':sum(annotation_matches), 'normalisation':'Remove Markdown blockquote markers, collapse whitespace; no spelling or punctuation changes.'},
        'pdf_inventory':pdfs,
        'term_counts_diagnostic_only':term_counts,
        'limitations':['No automatic readability score is used as a quality verdict.','The formal submitted thesis baseline is unresolved.','PDF extraction does not establish LaTeX-to-PDF identity.','No run or ground-truth provenance is established by text inspection.'],
    }
    out=LOCAL/'evaluator_baseline_diagnostics.json'
    out.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    print('Exact source quotation checks:',len(quote_checks))
    print('Unique annotation contents verified:',sum(annotation_matches),'/',len(unique))
    print('PDF page counts:',{k:v['page_count'] for k,v in pdfs.items()})
    print('Source files fingerprinted:',len(source_manifest))
    print('Previous proposal files fingerprinted without importing content:',len(previous_manifest))
    print('Wrote',out)

if __name__=='__main__':
    main()
